MVC_PERCENTILE = 99.0   # percentile of the amp contraction taken as 100% MVC
SPIKE_TRIM_FACTOR = 1.5  # clip rep envelopes above this × MVC (shift artefacts)
AMP_CATEGORY = "amp"    # the MVC-reference folder name (not a scored category)

# Burst detection thresholds the smoothed TKEO energy at baseline mean + k * SD
# (Hodges & Bui's k = 2-3 convention). SMOOTH_S is the moving-average width that turns
# instantaneous TKEO into a thresholdable activation envelope.
SMOOTH_S = 0.025
# Leniency ladder for rep_window(): try these thresholds (in SDs) hardest-first and
# accept the first burst spanning >= MIN_BOX_FRAC of the cued window. A weak, slow
# contraction sits low over the baseline, so the strict threshold clips it or misses
# it; relaxing recovers it. Bounded at 1.5 because below that the pre-cue baseline
# itself starts crossing (false activation rises 2% -> 12% from k=3 to k=1).
K_LADDER: Tuple[float, ...] = (3.0, 2.0, 1.5)
MIN_BOX_FRAC = 0.15
MERGE_GAP_S = 0.10      # bridge gaps shorter than this between active runs
# 0/1 flags aggregate by mean (-> a rate); box_k is a level and aggregates by median.
BINARY_FLAGS = ("truncated", "cue_missing", "box_fallback")
# Half-width of the window centred on the envelope peak used for S1. Short, because
# spectral estimates assume quasi-stationarity and dynamic movement violates it.
MDF_HALF_WINDOW_S = 0.125

_STAMP_RE = re.compile(r"^\d{4}-\d{2}-\d{2}_\d{6}_")

# Folder-name typos made during collection. The folder names are raw collected data
# and are not renamed on disk; they are reconciled here so the reps land in the cell
# they were actually recorded for.
CATEGORY_ALIASES: Dict[str, str] = {
    "kickfast": "kickbackfast",
    "kickslow": "kickbackslow",
}


def category_of(dataset_dir: Path) -> str:
    """Movement category = the folder name with its `YYYY-MM-DD_HHMMSS_` prefix
    stripped, so all reps of one movement share a category (`overheadfast`, ...).
    Known collection-time misspellings are mapped to the intended category."""
    name = Path(dataset_dir).name
    stripped = _STAMP_RE.sub("", name) or name
    return CATEGORY_ALIASES.get(stripped, stripped)


# --------------------------------------------------------------------------- #
#  Burst / rep segmentation
# --------------------------------------------------------------------------- #
def _runs(mask: np.ndarray) -> List[Tuple[int, int]]:
    """Half-open [start, end) index ranges of contiguous True in a bool mask."""
    if mask.size == 0:
        return []
    m = mask.astype(np.int8)
    edges = np.diff(np.concatenate(([0], m, [0])))
    starts = np.flatnonzero(edges == 1)
    ends = np.flatnonzero(edges == -1)
    return list(zip(starts.tolist(), ends.tolist()))


def _merge_runs(runs: List[Tuple[int, int]], merge_gap: int) -> List[Tuple[int, int]]:
    """Bridge [start, end) runs separated by <= `merge_gap` samples [R15]."""
    merged: List[Tuple[int, int]] = []
    for s, e in runs:
        if merged and s - merged[-1][1] <= merge_gap:
            # max(): a run nested inside the span it merges into must not shorten it
            merged[-1] = (merged[-1][0], max(e, merged[-1][1]))
        else:
            merged.append((s, e))
    return merged


def segment_reps(
    envelope: np.ndarray,
    fs: float,
    onset_frac: float = 0.20,
    min_rep_s: float = 0.12,
    merge_gap_s: float = 0.10,
) -> List[Tuple[int, int]]:
    """Amplitude-threshold onset detection over the envelope.

    A burst is a run where the envelope rises `onset_frac` of the way from its
    resting level (20th pct) to its peak (95th pct). Short runs are dropped and
    runs separated by < `merge_gap_s` are merged [R15]. Returns [start, end)
    sample ranges; empty when the signal is essentially flat.

    >>> MVC/amp FILE ONLY. The threshold is relative to *this recording's own*
    >>> percentile range, which fails on slow scored reps: when the burst fills much
    >>> of the file the 20th-pct "rest" creeps up into the contraction, raising the
    >>> threshold so the gradual rise crosses late and the box clamps around the
    >>> plateau — reading back a sharper onset/offset than really happened. Scored
    >>> reps use `rep_window()`, whose threshold comes from the quiet pre-cue
    >>> baseline instead. This function stays only because the amp file has no cue.
    """
    n = envelope.size
    if n == 0 or fs <= 0:
        return []
    rest = float(np.percentile(envelope, 20))
    peak = float(np.percentile(envelope, 95))
    span = peak - rest
    if span <= 1e-9:
        return []
    thr = rest + onset_frac * span

    reps = _runs(envelope > thr)
    if not reps:
        return []

    merged = _merge_runs(reps, int(round(merge_gap_s * fs)))
    min_len = max(1, int(round(min_rep_s * fs)))
    return [(s, e) for s, e in merged if e - s >= min_len]


def dominant_rep(envelope: np.ndarray, fs: float) -> Tuple[int, int]:
    """The single active burst of a one-rep file: the strongest run from
    `segment_reps` (by envelope peak). Falls back to the whole array when no burst
    is detected (e.g. a very short or flat recording)."""
    reps = segment_reps(envelope, fs)
    if not reps:
        return (0, envelope.size)
    return max(reps, key=lambda se: float(envelope[se[0]:se[1]].max())
               if se[1] > se[0] else 0.0)


TIME_NORM_LEN = 100     # samples in a time-normalised rep envelope profile


def rep_profile(seg: np.ndarray, n: int = TIME_NORM_LEN) -> Optional[np.ndarray]:
    """Resample a rep's envelope onto `n` points in [0,1] time so reps of different
    durations can be overlaid shape-for-shape.

    Presentational only — the viewer's overlay mode uses it. No §10.3 feature is
    derived from a time-normalised profile, because normalising away duration would
    discard exactly what T3 measures.
    """
    if seg.size < 2:
        return None
    xp = np.linspace(0.0, 1.0, seg.size)
    xq = np.linspace(0.0, 1.0, n)
    return np.interp(xq, xp, seg)


def _smooth_tkeo(tk: np.ndarray, fs: float, smooth_s: float = SMOOTH_S) -> np.ndarray:
    """Smoothed |TKEO| -> a thresholdable activation-energy envelope.

    TKEO output is *instantaneous* energy, dipping toward zero twice per carrier cycle
    even mid-burst, so thresholding it raw gives a shredded mask. A short moving
    average (`smooth_s`) turns it into the smooth envelope onset detection thresholds.
    """
    w = max(1, int(round(smooth_s * fs)))
    if w <= 1:
        return np.abs(tk)
    kern = np.ones(w, dtype=np.float64) / w
    return np.convolve(np.abs(tk), kern, mode="same")


def rep_window(ctx: "DatasetContext") -> Optional[Tuple[int, int, Optional[float], bool]]:
    """Detected burst boundaries for a scored rep: (start, end, k_used, fallback).

    Returns None when the recording has no movement cue (nothing anchors the search).

    The window is the active burst *containing the envelope peak*, found by
    thresholding the pre-cue-referenced activation energy. Search is confined to
    [cue, end]: the movement cannot precede the prompt, and excluding the pre-cue
    stretch keeps the detector out of the very baseline that sets its threshold.

    Leniency ladder: a weak, slow contraction sits low over the baseline, so the
    strict k=3 threshold clips or misses it. We try K_LADDER hardest-first and accept
    the first burst spanning >= MIN_BOX_FRAC of the cued window. If none qualifies we
    fall back to the whole cued window and flag it — better an honest "we could not
    localise this" than a box tuned down onto noise.
    """
    ci = ctx.cue_index()
    if ci is None:
        return None
    env, fs, n = ctx.envelope, ctx.fs, ctx.envelope.size
    win = n - ci
    if win < 2 or fs <= 0:
        return (ci, n, None, True)

    peak_i = ci + int(np.argmax(env[ci:]))
    energy = _smooth_tkeo(tkeo(ctx.filtered), fs)
    base = energy[:ci]
    merge_gap = int(round(MERGE_GAP_S * fs))
    best: Optional[Tuple[int, int]] = None

    if base.size >= 2:
        base_mean, base_sd = float(base.mean()), float(base.std())
        for k in K_LADDER:
            thr = base_mean + k * base_sd
            active = energy > thr
            active[:ci] = False                 # search only after the cue
            runs = _merge_runs(_runs(active), merge_gap)
            box = next(((s, e) for s, e in runs if s <= peak_i < e), None)
            if box is None:
                continue
            if best is None:
                best = box                      # remember the strictest box we found
            if (box[1] - box[0]) >= MIN_BOX_FRAC * win:
                return (box[0], box[1], k, False)

    if best is not None and (best[1] - best[0]) >= MIN_BOX_FRAC * win:
        return (best[0], best[1], K_LADDER[-1], False)
    return (ci, n, None, True)


def robust_max(envelope: np.ndarray, fs: float,
               pct: float = MVC_PERCENTILE) -> Optional[float]:
    """MVC reference: a high percentile of the amp contraction's envelope.

    Taken over the amp file's dominant burst (its actual contraction, not the rest
    before/after). The `pct`th percentile (default 99th) discards the top ~1% of
    samples — where a lone sensor-shift spike would sit — while still reflecting the
    true attainable peak, so one artefact can't define 100% MVC. A moving-average
    "sustained max" was tried first but sat well below real rep peaks and made every
    %MVC saturate; a percentile is on the same instantaneous scale as a rep's peak.
    """
    if envelope.size == 0 or fs <= 0:
        return None
    s, e = dominant_rep(envelope, fs)
    seg = envelope[s:e] if e > s else envelope
    if seg.size == 0:
        seg = envelope
    return float(np.percentile(seg, pct))


# --------------------------------------------------------------------------- #
#  Spectral helpers (shared by mains + spectral metrics)
# --------------------------------------------------------------------------- #
def _mains_residual(f: np.ndarray, fs: float, mains_hz: float) -> Optional[float]:
    if f.size < 64 or fs <= 0:
        return None
    nperseg = int(min(f.size, max(64, fs)))
    freqs, psd = signal.welch(f, fs=fs, nperseg=nperseg)
    total = float(np.sum(psd))
    if total <= 0:
        return None
    bw = 1.5
    band = np.zeros_like(freqs, dtype=bool)
    k = 1
    while mains_hz * k < 0.99 * (fs / 2.0):
        band |= (freqs >= mains_hz * k - bw) & (freqs <= mains_hz * k + bw)
        k += 1
    return float(np.sum(psd[band]) / total)


def _median_freq(x: np.ndarray, fs: float) -> Optional[float]:
    if x.size < 64 or fs <= 0:
        return None
    nperseg = int(min(x.size, max(64, fs)))
    freqs, psd = signal.welch(x, fs=fs, nperseg=nperseg)
    cumulative = np.cumsum(psd)
    if cumulative[-1] <= 0:
        return None
    return float(np.interp(cumulative[-1] / 2.0, cumulative, freqs))


