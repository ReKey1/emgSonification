@dataclass
class DatasetContext:
    """Everything loaded from one recording folder (one rep, or the amp file)."""
    subject: str
    dataset: str
    path: Path
    meta: dict
    cfg: Config
    fs: float
    t: np.ndarray
    raw: np.ndarray
    filtered: np.ndarray
    envelope: np.ndarray
    contact: np.ndarray            # float array, NaN where the flag was absent
    _rep: Optional[Tuple[int, int]] = field(default=None, repr=False)

    def rep(self) -> Tuple[int, int]:
        """[start, end) of this file's single dominant rep (cached).

        Amplitude-detected. Used for the MVC/amp file, which has no movement cue;
        scored reps use `rep_window()` instead.
        """
        if self._rep is None:
            self._rep = dominant_rep(self.envelope, self.fs)
        return self._rep

    def cue_index(self) -> Optional[int]:
        """Sample index of the movement cue (the third beep), or None if unstamped.

        `movement_onset_s` is seconds from the first recorded sample, written by
        Recorder.mark_movement(). Rejected when it falls outside the recording or
        leaves no usable pre-cue baseline. Anchors `rep_window()`'s burst search.
        """
        cue_s = self.meta.get("movement_onset_s")
        if cue_s is None or self.fs <= 0:
            return None
        i = int(round(float(cue_s) * self.fs))
        if i < 2 or i >= self.envelope.size:
            return None
        return i

    @property
    def category(self) -> str:
        return category_of(self.path)


def _read_signal_csv(path: Path) -> Dict[str, np.ndarray]:
    """Read signal.csv into named float columns; blank cells become NaN."""
    with open(path, "r", newline="", encoding="utf-8") as fh:
        reader = csv.reader(fh)
        header = next(reader, None)
        if not header:
            raise ValueError(f"empty signal file: {path}")
        cols: Dict[str, List[float]] = {h: [] for h in header}
        for line in reader:
            if not line:
                continue
            for h, cell in zip(header, line):
                cell = cell.strip()
                cols[h].append(float(cell) if cell else math.nan)
    return {h: np.asarray(v, dtype=np.float64) for h, v in cols.items()}


def load_dataset(dataset_dir: Path, recordings_root: Path,
                 stored: bool = False,
                 mains_hz: Optional[float] = None) -> DatasetContext:
    """Load one recording folder into a DatasetContext.

    By default `filtered`/`envelope` are **re-derived from raw with the zero-phase
    offline chain**, discarding the stored columns. Two reasons, both required by
    §10.3.1/§10.8: the stored columns came from the causal live chain, whose group
    delay biases timing measurements; and re-deriving guarantees every rep in the
    study passed through one frozen pipeline rather than whatever the live config
    happened to be that session.

    `stored=True` uses the recorded columns instead — what the subject actually heard
    through the sonifier. That is a playback/inspection mode, not a scoring mode.
    """
    dataset_dir = Path(dataset_dir)
    meta_path = dataset_dir / "session.json"
    meta: dict = {}
    if meta_path.exists():
        meta = json.loads(meta_path.read_text(encoding="utf-8"))
    cfg = Config.from_dict(meta.get("config", {})) if meta.get("config") else Config()
    if mains_hz is not None:
        cfg.mains_hz = mains_hz

    data = _read_signal_csv(dataset_dir / "signal.csv")
    if "raw" not in data:
        raise ValueError(f"{dataset_dir/'signal.csv'} has no 'raw' column")
    raw = data["raw"]
    fs = float(cfg.sample_rate)
    t = data.get("t")
    if t is None or t.size != raw.size:
        t = np.arange(raw.size, dtype=np.float64) / fs

    have_filtered = "filtered" in data and not np.all(np.isnan(data["filtered"]))
    have_envelope = "envelope" in data and not np.all(np.isnan(data["envelope"]))
    if stored and have_filtered and have_envelope:
        filtered = data["filtered"]
        envelope = data["envelope"]
    else:
        filtered, envelope = process_offline(cfg, raw)

    contact = data.get("contact_ok", np.full(raw.size, math.nan))

    try:
        rel = dataset_dir.resolve().relative_to(recordings_root.resolve())
        subject = rel.parts[0] if len(rel.parts) > 1 else ""
    except ValueError:
        subject = dataset_dir.parent.name

    return DatasetContext(
        subject=subject,
        dataset=dataset_dir.name,
        path=dataset_dir,
        meta=meta,
        cfg=cfg,
        fs=fs,
        t=t,
        raw=raw,
        filtered=np.asarray(filtered, dtype=np.float64),
        envelope=np.asarray(envelope, dtype=np.float64),
        contact=np.asarray(contact, dtype=np.float64),
    )


# --------------------------------------------------------------------------- #
#  Discovery: recordings -> subjects -> categories -> rep folders
# --------------------------------------------------------------------------- #
def find_datasets(recordings_root: Path) -> List[Path]:
    """Every folder under recordings_root that contains a signal.csv, sorted."""
    root = Path(recordings_root)
    if not root.exists():
        return []
    return sorted(p.parent for p in root.rglob("signal.csv"))


@dataclass
class SubjectGroup:
    """One test subject: their MVC (amp) folder and their movement categories."""
    subject: str
    amp_dir: Optional[Path]
    categories: Dict[str, List[Path]]   # category -> rep folders (sorted), no amp


def find_subjects(recordings_root: Path) -> List[SubjectGroup]:
    """Group every rep folder under recordings_root by subject then category.

    The subject is the folder directly under the recordings root; rep folders that
    sit in the root itself (old flat layout) are grouped under "(ungrouped)". The
    `amp` category is pulled aside as the subject's MVC reference.
    """
    root = Path(recordings_root)
    root_res = root.resolve()
    by_subject: Dict[str, List[Path]] = {}
    for d in find_datasets(root):
        parent = d.parent
        subject = "(ungrouped)" if parent.resolve() == root_res else parent.name
        by_subject.setdefault(subject, []).append(d)

    groups: List[SubjectGroup] = []
    for subject in sorted(by_subject):
        amp_dir: Optional[Path] = None
        categories: Dict[str, List[Path]] = {}
        for d in sorted(by_subject[subject]):
            cat = category_of(d)
            if cat == AMP_CATEGORY:
                if amp_dir is None:
                    amp_dir = d  # first amp folder is the MVC reference
                continue
            categories.setdefault(cat, []).append(d)
        groups.append(SubjectGroup(subject, amp_dir, categories))
    return groups


def subject_mvc(amp_dir: Optional[Path], recordings_root: Path,
                stored: bool = False, mains_hz: Optional[float] = None) -> Optional[float]:
    """Robust MVC reference (counts) for a subject from their amp recording, or
    None when there is no amp folder / it can't be loaded.

    Must go through the same chain as the reps it normalises — an MVC measured on a
    differently-filtered signal is not a valid denominator.
    """
    if amp_dir is None:
        return None
    try:
        ctx = load_dataset(amp_dir, recordings_root, stored=stored, mains_hz=mains_hz)
    except Exception:
        return None
    return robust_max(ctx.envelope, ctx.fs)


# --------------------------------------------------------------------------- #
#  Scoring one rep, then aggregating a category
# --------------------------------------------------------------------------- #
def score_rep(ctx: DatasetContext,
              mvc: Optional[float]) -> Dict[str, Optional[float]]:
    """The five §10.3 features plus quality metrics for one rep file.

    The scored window is the detected burst from `rep_window()` — the active run
    containing the envelope peak, its onset found relative to the quiet pre-cue
    baseline so a slow rise is not clipped. When the burst cannot be localised the
    window falls back to [cue, end] and `box_fallback` is set; T3 is then None, since
    a whole-window box makes it meaningless.

    When an MVC is given, the envelope is clipped above SPIKE_TRIM_FACTOR × MVC first,
    so a sensor-shift spike cannot define either the peak (A1) or the slope (T1/T2) —
    but normal dynamic overshoot is preserved, which is why %MVC is not capped at 100.

    Every feature is None rather than 0 when it cannot be computed; a missing
    measurement must never be averaged in as if it were a small one.
    """
    env = ctx.envelope
    filt = ctx.filtered
    fs = ctx.fs
    row: Dict[str, Optional[float]] = {k: None for k in REP_METRIC_COLUMNS}

    cue = ctx.cue_index()
    row["cue_missing"] = 0.0 if cue is not None else 1.0

    window = rep_window(ctx)
    if window is not None:
        s, e, k_used, fallback = window
        row["box_fallback"] = float(fallback)
        row["box_k"] = k_used
    else:
        # No cue: fall back to amplitude detection so an unstamped recording still
        # yields quality metrics, but the features stay None — they are only
        # meaningful against the protocol's own window.
        s, e = ctx.rep()
        fallback = True

    rep_env = env[s:e]
    rep_filt = filt[s:e]
    rest_filt = filt[:s]

    ceil = mvc * SPIKE_TRIM_FACTOR if (mvc and mvc > 0) else None
    rep_env_c = np.minimum(rep_env, ceil) if ceil else rep_env

    # ---- signal quality (always computed) ---------------------------------
    base = float(np.sqrt(np.mean(rest_filt ** 2))) if rest_filt.size else None
    row["baseline_noise"] = base
    if base and base > 0 and rep_filt.size:
        rms_act = float(np.sqrt(np.mean(rep_filt ** 2)))
        row["snr_db"] = 20.0 * math.log10(rms_act / base)
    row["mains_residual"] = _mains_residual(filt, fs, ctx.cfg.mains_hz)

    c = ctx.contact
    valid = c[~np.isnan(c)] if c.size else c
    row["contact_frac"] = float(np.mean(valid)) if valid.size else None

    if window is None or rep_env_c.size < 2 or fs <= 0:
        return row

    # Truncated = the detected burst runs into the last sample: the recording stopped
    # while the muscle was still active, so the offset (and T2/T3) were never seen.
    row["truncated"] = float(e >= env.size)

    peak_i = int(np.argmax(rep_env_c))
    peak = float(rep_env_c[peak_i])

    # ---- A1: peak amplitude, %MVC ----------------------------------------
    if mvc and mvc > 0:
        row["a1_peak_pct_mvc"] = peak / mvc * 100.0

    # ---- T1 / T2: envelope slope on the rise and the fall ------------------
    # One derivative of the box, split at the peak. The rising phase runs onset ->
    # peak and the falling phase peak -> offset, so each max() picks the steepest
    # excursion in its own direction. Boundary-insensitive (a max over any adequate
    # box), which is why they held up even under the cue-window definition.
    if mvc and mvc > 0:
        d = np.gradient(rep_env_c, 1.0 / fs)
        rise, fall = d[:peak_i + 1], d[peak_i:]
        if rise.size:
            row["t1_rer_pct_mvc_s"] = float(rise.max()) / mvc * 100.0
        # A peak at the very end leaves no falling phase: max(-dE/dt) would be
        # negative (a still-rising envelope), not a rate of decay. Report nothing —
        # the deactivation was never observed. `truncated` marks these.
        if fall.size >= 2:
            decay = float((-fall).max())
            if decay > 0:
                row["t2_offset_rate_pct_mvc_s"] = decay / mvc * 100.0

    # ---- T3: burst duration as a fraction of the cued movement window ------
    # §10.3's (t_offset - t_onset) / movement duration, with the burst boundaries from
    # rep_window() and the movement window measured from the cue (so variable pre-cue
    # dead time stays out of the denominator). Undefined on a fallback box, which
    # spans the whole window and would force T3 = 1.
    if not fallback and cue is not None and e > cue:
        row["t3_burst_frac"] = (e - s) / (env.size - cue)

    # ---- S1: median frequency over the burst plateau -----------------------
    # On the band-passed signal — rectifying and smoothing to an envelope destroys
    # the spectrum. Short window centred on the peak, per the stationarity caveat.
    half = max(1, int(round(MDF_HALF_WINDOW_S * fs)))
    a = max(0, s + peak_i - half)
    b = min(filt.size, s + peak_i + half)
    plateau = filt[a:b]
    row["s1_mdf_hz"] = _median_freq(plateau if plateau.size >= 64 else rep_filt, fs)

    return row


def _finite(values) -> List[float]:
    return [float(v) for v in values
            if v is not None and not (isinstance(v, float) and math.isnan(v))]


def _nanmedian(values) -> Optional[float]:
    xs = _finite(values)
    return float(np.median(xs)) if xs else None


def _nanmean(values) -> Optional[float]:
    xs = _finite(values)
    return float(np.mean(xs)) if xs else None


def rep_row(ctx: DatasetContext, subject: str, category: str,
            mvc: Optional[float]) -> Dict[str, object]:
    """One reps.csv row: identity + the five features + flags + quality."""
    row: Dict[str, object] = {
        "subject": subject,
        "category": category,
        "rep": ctx.dataset,
        "started": ctx.meta.get("started", ""),
        "duration_s": ctx.meta.get("duration_s", round(ctx.raw.size / ctx.fs, 3)),
        "n_samples": ctx.raw.size,
        "sample_rate": int(ctx.fs),
        "mains_hz": ctx.cfg.mains_hz,
    }
    row.update(score_rep(ctx, mvc))
    return row


def aggregate_category(subject: str, category: str, mvc: Optional[float],
                       rep_rows: List[Dict[str, object]],
                       weights: Optional["QualityWeights"] = None) -> Dict[str, object]:
    """Collapse a category's rep rows into one scores.csv row.

    Features and quality metrics are aggregated by MEDIAN, per §10.4 step 1 — one
    fumbled rep should not move the cell. The 0/1 flags (BINARY_FLAGS) aggregate by
    MEAN, giving the *rate* (fraction truncated / fallback), which is what reporting
    needs. box_k is a threshold level, not a rate, so it stays on the median.
    """
    cat: Dict[str, object] = {
        "subject": subject,
        "category": category,
        "n_reps": len(rep_rows),
        "mvc_reference": round(mvc, 4) if mvc else None,
    }
    for col in REP_METRIC_COLUMNS:
        values = [r.get(col) for r in rep_rows]
        cat[col] = _nanmean(values) if col in BINARY_FLAGS else _nanmedian(values)
    cat[SCORE_COLUMN] = composite_quality(cat, weights)
    return cat


# --------------------------------------------------------------------------- #
#  Composite signal-quality gate  (transparent + reconfigurable)
# --------------------------------------------------------------------------- #
@dataclass
class QualityWeights:
    """Knobs for composite_quality(). Defaults are a documented heuristic, not a
    law — the research fixes only that a quality gate must *exist* (exclude noisy
    reps), not its exact form. Tune freely for your rig."""
    snr_floor_db: float = 3.0
    snr_good_db: float = 20.0
    mains_tol: float = 0.20
    w_snr: float = 0.6
    w_mains: float = 0.4


def _clamp01(x: float) -> float:
    return 0.0 if x < 0.0 else 1.0 if x > 1.0 else x


def composite_quality(row: Dict[str, object],
                      w: Optional[QualityWeights] = None) -> Optional[float]:
    """0..1 signal-integrity score: is this (aggregated) recording clean enough to
    trust? Blends SNR + mains sub-scores (reweighted to whatever is present) then
    gates on contact fraction. None when no quality evidence exists. Excludes the
    motor-learning metrics — those describe the movement, not signal usability."""
    w = w or QualityWeights()
    parts: List[Tuple[float, float]] = []

    snr = row.get("snr_db")
    if snr is not None and w.snr_good_db > w.snr_floor_db:
        parts.append((w.w_snr, _clamp01(
            (float(snr) - w.snr_floor_db) / (w.snr_good_db - w.snr_floor_db))))

    mains = row.get("mains_residual")
    if mains is not None and w.mains_tol > 0:
        parts.append((w.w_mains, _clamp01(1.0 - float(mains) / w.mains_tol)))

    if not parts:
        return None
    total_w = sum(wt for wt, _ in parts)
    base = sum(wt * sub for wt, sub in parts) / total_w if total_w > 0 else 0.0

    contact = row.get("contact_frac")
    gate = float(contact) if contact is not None else 1.0
    return _clamp01(base * gate)


# --------------------------------------------------------------------------- #
#  Scoring everything
# --------------------------------------------------------------------------- #
def score_all(recordings_root: Path, stored: bool = False,
              mains_hz: Optional[float] = None,
              weights: Optional[QualityWeights] = None,
              ) -> Tuple[List[Dict[str, object]], List[Dict[str, object]],
                         List[Tuple[Path, str]]]:
    """Score every subject/category under recordings_root.

    Returns (category_rows, rep_rows, failures): one aggregated row per
    (subject, category), one row per rep file, and (path, error) for reps that
    could not be loaded. The amp folders are used as MVC references, not scored.
    """
    category_rows: List[Dict[str, object]] = []
    rep_rows: List[Dict[str, object]] = []
    failures: List[Tuple[Path, str]] = []
    root = Path(recordings_root)

    for group in find_subjects(root):
        mvc = subject_mvc(group.amp_dir, root, stored=stored, mains_hz=mains_hz)
        for category in sorted(group.categories):
            rows: List[Dict[str, object]] = []
            for d in group.categories[category]:
                try:
                    ctx = load_dataset(d, root, stored=stored, mains_hz=mains_hz)
                except Exception as exc:
                    failures.append((d, f"{type(exc).__name__}: {exc}"))
                    continue
                rows.append(rep_row(ctx, group.subject, category, mvc))
            if not rows:
                continue
            rep_rows.extend(rows)
            category_rows.append(
                aggregate_category(group.subject, category, mvc, rows, weights))

    category_rows.sort(key=lambda r: (str(r["subject"]), str(r["category"])))
    rep_rows.sort(key=lambda r: (str(r["subject"]), str(r["category"]), str(r["rep"])))
    return category_rows, rep_rows, failures


# --------------------------------------------------------------------------- #
#  CSV output
# --------------------------------------------------------------------------- #
def _fmt(value: object) -> str:
    """Format a cell for CSV: blanks for None/NaN, ~4 significant figures."""
    if value is None:
        return ""
    if isinstance(value, float):
        if math.isnan(value):
            return ""
        return f"{value:.4g}"
    return str(value)


def header_labels(columns: Tuple[str, ...]) -> List[str]:
    """Header row for `columns`: each labelled with its unit where it has one."""
    return [COLUMN_LABELS.get(c, c) for c in columns]


def write_csv(rows: List[Dict[str, object]], out_path: Path,
              columns: Tuple[str, ...]) -> Path:
    """Write rows to a clean CSV in the given column order, with unit-labelled
    headers (data stays keyed by the bare column names)."""
    out_path = Path(out_path)
    out_path.parent.mkdir(parents=True, exist_ok=True)
    with open(out_path, "w", newline="", encoding="utf-8") as fh:
        writer = csv.writer(fh)
        writer.writerow(header_labels(columns))
        for row in rows:
            writer.writerow([_fmt(row.get(col)) for col in columns])
    return out_path
